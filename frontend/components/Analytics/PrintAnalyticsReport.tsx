"use client"

import { createPortal } from "react-dom"
import type { WasteClassification, WasteCompositionItem } from "@/types/analytics"
import type { TopBarangay } from "@/lib/analytics"
import { formatWeight, formatWeightIn, pickWeightUnit } from "@/lib/formatWeight"

type Props = {
  generatedBy: string
  from: string // "YYYY-MM-DD"
  to: string // "YYYY-MM-DD"
  composition: WasteCompositionItem[]
  barangays: TopBarangay[]
  records: WasteClassification[]
}

const CATEGORIES: { title: string; key: keyof WasteClassification }[] = [
  { title: "Biodegradable", key: "biodegradable_pct" },
  { title: "Recyclable", key: "recyclable_pct" },
  { title: "Residual", key: "residual_pct" },
  { title: "Special Waste", key: "special_waste_pct" },
]

const DATE_TIME: Intl.DateTimeFormatOptions = {
  month: "short", day: "numeric", year: "numeric", hour: "2-digit", minute: "2-digit",
}

const dayLabel = (d: string) =>
  new Date(`${d}T00:00:00`).toLocaleDateString("en-US", { month: "short", day: "numeric", year: "numeric" })

const pct = (v: unknown) => `${Number(v).toFixed(2)}%`

// Same table markup as PrintReport, so it picks up the same print styles
function PrintTable({ columns, rows }: { columns: string[]; rows: (string | number)[][] }) {
  return (
    <table className="print-table">
      <thead>
        <tr>{columns.map(c => <th key={c}>{c}</th>)}</tr>
      </thead>
      <tbody>
        {rows.length === 0 ? (
          <tr><td colSpan={columns.length}>No data in this period.</td></tr>
        ) : (
          rows.map((row, i) => (
            <tr key={i}>{row.map((cell, j) => <td key={j}>{cell}</td>)}</tr>
          ))
        )}
      </tbody>
    </table>
  )
}

const sectionTitle: React.CSSProperties = {
  fontWeight: 700,
  fontSize: 12,
  margin: "16px 0 0",
  color: "#122A48",
}

// Print-only report for the Analytics page. Styled by the same global print CSS
// as PrintReport; trigger it with printReport() like the other pages.
export function PrintAnalyticsReport({ generatedBy, from, to, composition, barangays, records }: Props) {
  if (typeof document === "undefined") return null

  const generatedAt = new Date().toLocaleString("en-PH", DATE_TIME)
  const period = from === to ? dayLabel(from) : `${dayLabel(from)} – ${dayLabel(to)}`

  // volume per waste type, from the raw records
  const typeVolume: Record<string, number> = {}
  for (const { title, key } of CATEGORIES) {
    typeVolume[title] = records.reduce(
      (sum, w) => sum + ((w.estimated_volume || 0) * ((w[key] as number) || 0)) / 100,
      0
    )
  }
  const typeUnit = pickWeightUnit(Object.values(typeVolume))

  const compositionRows = composition.map(c => [
    c.type,
    formatWeightIn(typeVolume[c.type] ?? 0, typeUnit),
    `${c.percent}%`,
  ])

  const barangayUnit = pickWeightUnit(barangays.map(b => b.total))
  const barangayRows = barangays.map((b, i) => [
    i + 1,
    b.name,
    formatWeightIn(b.total, barangayUnit),
    ...CATEGORIES.map(c => formatWeightIn(b.breakdown[c.title] ?? 0, barangayUnit)),
    b.topType,
  ])

  // same columns and formatting as the Waste Classification report
  const recordRows = [...records]
    .sort((a, b) => b.classification_id - a.classification_id)
    .map(c => [
      c.classification_id,
      c.node_details?.node_name ?? "—",
      c.node_details?.barangay_details?.barangay_name ?? "—",
      c.dominant_waste_type,
      pct(c.recyclable_pct),
      pct(c.biodegradable_pct),
      pct(c.residual_pct),
      pct(c.special_waste_pct),
      pct(c.confidence),
      formatWeight(Number(c.estimated_volume)),
      c.timestamp ? new Date(c.timestamp).toLocaleString("en-PH", DATE_TIME) : "—",
    ])

  const content = (
    <div className="print-report">
      <div className="print-header">
        <img src="/ROS-logo.jpg" className="print-logo" alt="" />
        <div className="print-header-text">
          <p>Republic of the Philippines</p>
          <p>Province of La Union</p>
          <p className="print-municipality">Municipality Of Rosario</p>
        </div>
      </div>
      <div className="print-divider" />
      <div className="print-title-block">
        <p className="print-office">Waste Analytics</p>
        <p className="print-meta">
          Generated by <span className="print-generated-by">{generatedBy}</span>
          &nbsp;|&nbsp; {generatedAt} &nbsp;|&nbsp; {records.length} records
        </p>
        <p className="print-meta">Period: {period}</p>
      </div>

      <p style={sectionTitle}>Classified Waste Type</p>
      <PrintTable columns={["Waste Type", "Estimated Volume", "Share"]} rows={compositionRows} />

      <p style={sectionTitle}>Barangays with Waste Data</p>
      <PrintTable
        columns={["#", "Barangay", "Total Waste", ...CATEGORIES.map(c => c.title), "Most Common Type"]}
        rows={barangayRows}
      />

      <p style={sectionTitle}>Waste Classification Records</p>
      <PrintTable
        columns={["ID", "Node", "Location", "Dominant Type", "Recyclable", "Biodegradable", "Residual", "Special Waste", "Confidence", "Est. Volume", "Timestamp"]}
        rows={recordRows}
      />

      <div className="print-footer">AGOS — Automated Geo-Based Obstruction Sensing System</div>
    </div>
  )

  return createPortal(content, document.body)
}